  // ---------------------------------------------------------------- form
  // how much a performance at one level counts towards selection for another: weight (how much it is looked at)
  // and value (runs/wickets scaled to the target level: 2nd XI runs are cheaper than Shield runs)
  const LVW = { shield: { seconds: 0.7, shield: 1, test: 1.2, county: 0.85 }, test: { seconds: 0.4, shield: 0.8, test: 1, county: 0.65 }, seconds: { seconds: 1, shield: 1.2, test: 1.3, county: 1.1 }, county: { seconds: 0.5, shield: 0.9, test: 1, county: 1 } };
  const LVV = { shield: { seconds: 0.75, shield: 1, test: 1.15, county: 0.95 }, test: { seconds: 0.6, shield: 0.85, test: 1, county: 0.8 }, seconds: { seconds: 1, shield: 1.2, test: 1.3, county: 1.15 }, county: { seconds: 0.75, shield: 1, test: 1.1, county: 1 } };
  const BENCH = { bat: { seconds: 36, shield: 33, test: 38, county: 32 }, wpm: { seconds: 3.6, shield: 3.2, test: 3.4, county: 3.3 } };
  CB.form = function (p, forLevel) {
    const w = LVW[forLevel], v = LVV[forLevel];
    let R = 0, O = 0, n = 0, wk = 0, rc = 0, bm = 0;
    for (const m of p.rec.slice(-8)) {
      const f = w[m.lv] || 0.5, val = v[m.lv] || 0.7;
      for (const b of m.bat) { R += f * b[0] * val; O += f * (b[1] ? 1 : 0); n += f; }
      if (m.b > 30) { wk += f * m.w * val; rc += f * m.rc / val; bm += f; }
    }
    const bench = BENCH.bat[forLevel];
    const avg = R / Math.max(0.7, O);
    const fb = n ? 9 * Math.max(-1, Math.min(1.2, (avg - bench) / bench)) * n / (n + 4) : 0;
    let fw = 0;
    if (bm) {
      const wpm = wk / bm, bavg = rc / Math.max(0.7, wk);
      fw = (6 * Math.max(-1, Math.min(1.2, (wpm - BENCH.wpm[forLevel]) / BENCH.wpm[forLevel])) + 3 * Math.max(-1, Math.min(1, (28 - bavg) / 28))) * bm / (bm + 3);
    }
    return { bat: fb, bowl: fw };
  };

  // ---------------------------------------------------------------- selection
  // XI: 2 openers, 3 top order, a #6 (batter or all-rounder), keeper, 4 bowlers (pace/spin mix by conditions)
  CB.pickXI = function (W, pool, level, opt) {
    opt = opt || {};
    const P = pool.map(id => W.players[id]).filter(p => p && !(p.inj > 0));
    const prev = new Set(opt.prev || []);
    const bonus = p => (prev.has(p.id) ? (opt.inc != null ? opt.inc : 3) : 0) + (p.user && p.perkSel ? p.perkSel : 0) + (p.id === opt.force ? 500 : 0);
    const F = new Map(P.map(p => [p.id, CB.form(p, level)]));
    const bat = p => CB.batVal(p) + p.bias + F.get(p.id).bat + bonus(p);
    const bowl = p => CB.bowlVal(p) + p.bias + F.get(p.id).bowl + bonus(p);
    const used = new Set();
    const take = (cands, score, n) => { const c = cands.filter(p => !used.has(p.id)).sort((a, b) => score(b) - score(a)).slice(0, n); c.forEach(p => used.add(p.id)); return c; };
    const keeper = take(P.filter(p => p.role === 'wk'), p => CB.keepVal(p) + p.bias + F.get(p.id).bat * 0.5 + bonus(p), 1);
    if (!keeper.length) keeper.push(...take(P, p => p.a.KEEP + bonus(p), 1));
    const openers = take(P.filter(p => ['open', 'top'].includes(p.role)), p => bat(p) + (p.role === 'open' ? 4 : 0), 2);
    const top = take(P.filter(p => ['top', 'mid', 'open'].includes(p.role)), bat, 3);
    // bowlers: spinners per conditions
    const nSpin = opt.spinners != null ? opt.spinners : 1;
    const spinC = P.filter(p => CB.isSpinner(p) && ['spin', 'ar'].includes(p.role) && !used.has(p.id)).sort((a, b) => bowl(b) - bowl(a));
    const paceC = P.filter(p => !CB.isSpinner(p) && ['pace', 'ar'].includes(p.role) && !used.has(p.id)).sort((a, b) => bowl(b) - bowl(a));
    // first spinner if he's within reach of the 4th quick (or conditions demand one), a second only if nearly as good as the 3rd
    const spinners = [];
    for (const s of spinC) {
      if (spinners.length >= nSpin) break;
      const rival = paceC[3 - spinners.length], cut = spinners.length === 0 ? (opt.mustSpin ? 99 : 8) : 3;
      if (!rival || bowl(s) > bowl(rival) - cut) spinners.push(s);
    }
    spinners.forEach(p => used.add(p.id));
    // #6: best of batter-ish or all-rounder value
    const six = take(P.filter(p => ['mid', 'top', 'ar', 'open'].includes(p.role)), p => p.role === 'ar' ? 0.65 * bat(p) + 0.45 * bowl(p) : bat(p) - 1, 1);
    const quicks = take(P.filter(p => ['pace', 'ar'].includes(p.role) && !CB.isSpinner(p)), bowl, 4 - spinners.length);
    let xi = openers.concat(top, six, keeper, quicks, spinners);
    // fill gaps (injuries) with best remaining
    if (xi.length < 11) xi = xi.concat(take(P, p => Math.max(bat(p), bowl(p)), 11 - xi.length));
    // still short (injury crisis): carry the walking wounded rather than play with ten
    if (xi.length < 11) { const hurt = pool.map(id => W.players[id]).filter(p => p && p.inj > 0 && !used.has(p.id)); xi = xi.concat(hurt.slice(0, 11 - xi.length)); }
    // batting order: top seven fixed by slot, tail by batting
    const head = openers.concat(top, six, keeper), tail = xi.filter(p => !head.includes(p)).sort((a, b) => CB.batVal(b) - CB.batVal(a));
    return head.concat(tail).slice(0, 11).map(p => p.id);
  };

  function teamFromIds(W, ids, name, short) {
    const xi = ids.map(id => W.players[id]);
    xi.forEach(p => CB.prepMatchPlayer && CB.prepMatchPlayer(p));
    const k = xi.findIndex(p => p.role === 'wk');
    const u = xi.find(p => p.user);
    return { name, short, ids, prefs: u ? u.captPrefs || null : null, xi: xi.map(p => Object.assign({ id: p.id, name: p.first + ' ' + p.last, short: CB.shortName(p), role: p.role, user: !!p.user }, { e: p.e, bw: p.bw })), keeper: k >= 0 ? k : 6 };
  }
